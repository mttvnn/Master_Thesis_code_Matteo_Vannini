def detect_mat_format(mat_path):
    with open(mat_path, 'rb') as f:
        header = f.read(128)
    return 'v7.3' if header[:8] == b'\x89HDF\r\n\x1a\n' else 'v7_or_earlier'


def _has(container, key, is_v73):
    return key in container.keys() if is_v73 else hasattr(container, key)


def _get(container, key, is_v73):
    return container[key] if is_v73 else getattr(container, key)


def _fields(container, is_v73):
    if is_v73:
        return list(container.keys())
    return [a for a in dir(container) if not a.startswith('_')]



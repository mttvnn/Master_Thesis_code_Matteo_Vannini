class PhamHeightProminenceTunable(PhamPosturalTransitionDetection):
    """Identical to the original KielMAT implementation (same boundary search by zero crossings, same tilt-angle formula, same classification);
    the only difference is that the height and prominence of the peaks of the denoised tilt signal, hard-coded to 0.2/0.2 and not exposed by the
    constructor, are configurable. No other line of the original logic was modified (checked line by line)."""

    def __init__(self, *args, height=0.2, prominence=0.2, **kwargs):
        super().__init__(*args, **kwargs)
        self.height = height
        self.prominence = prominence

    def detect(self, accel_data, gyro_data, sampling_freq_Hz, dt_data=None,
               tracking_system=None, tracked_point=None, plot_results=False):
        sampling_period = 1 / sampling_freq_Hz
        gyro_data_rad = np.deg2rad(gyro_data)
        accel_data_arr = np.ascontiguousarray(accel_data)
        self.gyro_data = np.ascontiguousarray(gyro_data_rad)

        vqf = VQF(sampling_period)
        out_orientation_est = vqf.updateBatch(self.gyro_data, accel_data_arr)

        accel_updated = np.zeros_like(accel_data_arr)
        gyro_updated = np.zeros_like(self.gyro_data)
        for t in range(accel_updated.shape[0]):
            accel_updated[t, :] = vqf.quatRotate(out_orientation_est["quat6D"][t, :], accel_data_arr[t, :])
        for t in range(gyro_updated.shape[0]):
            gyro_updated[t, :] = vqf.quatRotate(out_orientation_est["quat6D"][t, :], self.gyro_data[t, :])

        accel = accel_updated / 9.81
        self.gyro = np.rad2deg(gyro_updated)

        range_x = np.ptp(self.gyro[:, 0])
        range_y = np.ptp(self.gyro[:, 1])
        var_x = np.var(self.gyro[:, 0])
        var_y = np.var(self.gyro[:, 1])

        if range_x > range_y or var_x > var_y:
            self.gyro_mediolateral = self.gyro[:, 0]
        else:
            self.gyro_mediolateral = self.gyro[:, 1]

        time = np.arange(1, len(accel[:, 0]) + 1) * sampling_period

        tilt_angle_deg = _kielmat_preproc_module.tilt_angle_estimation(
            data=self.gyro_mediolateral, sampling_frequency_hz=sampling_freq_Hz
        )
        tilt_angle_rad = np.deg2rad(tilt_angle_deg)
        tilt_sin = np.sin(tilt_angle_rad)

        tilt_dwt_3 = _kielmat_preproc_module.wavelet_decomposition(data=tilt_sin, level=3, wavetype="coif5")
        tilt_dwt_10 = _kielmat_preproc_module.wavelet_decomposition(data=tilt_sin, level=10, wavetype="coif5")
        tilt_dwt = tilt_dwt_3 - tilt_dwt_10

        # ===================== Only one difference: height/prominence configurable =====================
        self.local_peaks, _ = scipy.signal.find_peaks(tilt_dwt, height=self.height, prominence=self.prominence)
        # ==================================================================================================


        iZeroCr = np.where((self.gyro_mediolateral[:-1] * self.gyro_mediolateral[1:]) < 0)[0]
        gyro_y_diff = np.diff(self.gyro_mediolateral, axis=0)
        self.left_side = np.ones_like(self.local_peaks)
        self.right_side = len(self.gyro_mediolateral) * np.ones_like(self.local_peaks)

        for i in range(len(self.local_peaks)):
            postural_transitions = self.local_peaks[i]
            dist2peak = iZeroCr - postural_transitions
            dist2peak_left_side = dist2peak[dist2peak < 0]
            dist2peak_right_side = dist2peak[dist2peak > 0]

            for j in range(len(dist2peak_left_side) - 1, -1, -1):
                if gyro_y_diff[postural_transitions + dist2peak_left_side[j]] < 0 and -dist2peak_left_side[j] > (0.2 * sampling_freq_Hz):
                    if j > 0:
                        if (dist2peak_left_side[j] - dist2peak_left_side[j - 1]) >= (0.2 * sampling_freq_Hz) or (
                            tilt_angle_deg[postural_transitions + dist2peak_left_side[j - 1]]
                            - tilt_angle_deg[postural_transitions + dist2peak_left_side[j]]
                        ) > 1:
                            self.left_side[i] = postural_transitions + dist2peak_left_side[j]
                            break
                        else:
                            self.left_side[i] = postural_transitions + dist2peak_left_side[j]
                            break
            for j in range(len(dist2peak_right_side)):
                if gyro_y_diff[postural_transitions + dist2peak_right_side[j]] < 0 and dist2peak_right_side[j] > (0.2 * sampling_freq_Hz):
                    self.right_side[i] = postural_transitions + dist2peak_right_side[j]
                    break

            self.postural_transition_angle = np.abs(tilt_angle_deg[self.local_peaks] - tilt_angle_deg[self.left_side])
            if self.left_side[0] == 1:
                self.postural_transition_angle[0] = abs(
                    tilt_angle_deg[self.local_peaks[0]] - tilt_angle_deg[self.right_side[0]]
                )

            duration = (self.right_side - self.left_side) / sampling_freq_Hz
            postural_transition_onset = time[self.local_peaks]

        i = self.postural_transition_angle >= self.min_postural_transition_angle_deg
        postural_transition_onset = self.left_side[i] / sampling_freq_Hz
        duration = duration[i]

        postural_transitions_ = pd.DataFrame({
            "onset": postural_transition_onset,
            "duration": duration,
            "event_type": "postural transition",
            "tracking_systems": tracking_system,
            "tracked_points": tracked_point,
        })
        self.postural_transitions_ = postural_transitions_
        return self


def _collect_pham_events(accel_data, gyro_data, fs, cutoff_freq_hz, angle, height, prominence, want_type):
    """Implements PhamHeightProminenceTunable (minimal subclass: only height/prominence
    are configurable; the rest is identical to the original) and returns the list of events
    (t_start_s, t_end_s) of the requested type (want_type=‘STS’ or ‘SdS’), using the
    native spatio_temporal_parameters() method."""
    pham = PhamHeightProminenceTunable(cutoff_freq_hz=cutoff_freq_hz, min_postural_transition_angle_deg=angle,
                                          height=height, prominence=prominence)
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", category=UserWarning)
            pham.detect(accel_data=accel_data, gyro_data=gyro_data, sampling_freq_Hz=int(fs),
                        tracking_system="imu", tracked_point="LowerBack", plot_results=False)
            pham.spatio_temporal_parameters()
    except Exception:
        return []

    if pham.postural_transitions_ is None or len(pham.postural_transitions_) == 0:
        return []

    want_label = "sit to stand" if want_type == "STS" else "stand to sit"
    events = []
    for (_, row), (_, param_row) in zip(pham.postural_transitions_.iterrows(), pham.parameters_.iterrows()):
        if param_row['type_of_postural_transition'] == want_label:
            t_start = row['onset']
            t_end = t_start + row['duration']
            events.append((t_start, t_end))
    return events



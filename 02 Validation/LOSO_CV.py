def _iou_r2(a, b, fs=100):
    t0, t1 = min(a[0], b[0]), max(a[1], b[1])
    n = max(int(round((t1 - t0) * fs)), 1)
    t = np.linspace(t0, t1, n, endpoint=False)
    va, vb = (t >= a[0]) & (t < a[1]), (t >= b[0]) & (t < b[1])
    if not va.any() and not vb.any():
        return 0.0
    return float((va & vb).sum() / (va | vb).sum())

def _eval_strict(gt, pred, iou_threshold=0.5, fs=100):

    used, tp, fp = set(), 0, 0
    for p in pred:
        best, best_i = 0.0, -1
        for i, g in enumerate(gt):
            if i in used:
                continue
            v = _iou_r2(p, g, fs)
            if v > best:
                best, best_i = v, i
        if best >= iou_threshold:
            tp += 1
            used.add(best_i)
        else:
            fp += 1
    return tp, fp


def _eval_chunk(acc1, gyr1, ts, gt, want_label, base_params, chunk):
    import warnings
    from jas_detector import JASDetector
    out = []
    for params in chunk:
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                preds = JASDetector(verbose=False, **base_params, **params).predict(accel=acc1, gyro=gyr1, time=ts)
        except Exception:
            preds = None
        if preds is None or len(preds) == 0:
            pred = []
        else:
            pred = [(float(r.start_time), float(r.end_time)) for r in preds.itertuples()
                    if r.transition_type == want_label]
        out.append(_eval_strict(gt, pred))
    return out



    rep_r2, chosen = loso_r2(res, gold_n, combos)
    print_report(rep_r2, f"JAS {event_type} — LOSO ROUND 1+2")

    keys = [str(sorted(c.items())) for _, c in chosen]
    best_key, count = Counter(keys).most_common(1)[0]
    combo_r2 = next(c for _, c in chosen if str(sorted(c.items())) == best_key)
    print(f"\nCombo round 2 piu' scelta ({count}/{len(chosen)} fold): {combo_r2}")

    f1_r1 = ref_r1['Overall (Test4+Test8+Test11)']['F1']
    f1_r2 = rep_r2['Overall (Test4+Test8+Test11)']['F1']
    if f1_r2 >= f1_r1:
        label, final, final_report = 'round1+2', {**r1_params, **combo_r2}, rep_r2
        print(f"[JAS {event_type}] Round 2 MANTAINED (F1 {f1_r2:.1%} >= only round 1 {f1_r1:.1%})")
    else:
        label, final, final_report = 'round1_only', {**r1_params, **r2_defaults}, ref_r1
        print(f"[JAS {event_type}] Round 2 DISCHARGED (F1 {f1_r2:.1%} < only round 1 {f1_r1:.1%})")
    print(f"JAS {event_type} — combo FINALE ({label}): {final}")

    overall = final_report['Overall (Test4+Test8+Test11)']
    final_row = {'Event': event_type, 'Source': label, 'Fold_agreement': f"{count}/{len(chosen)}",
                 **{k: overall[k] for k in ['TP', 'FP', 'FN', 'Precision', 'Sensitivity', 'F1']},
                 **final}
    return all_combos_table(res, gold_n, combos, event_type), final_row



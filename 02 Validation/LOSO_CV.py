class StillnessTunable(Stillness):
    """Identical to the original Stillness class of sit2standpy
    (same detection logic, integration and quantification); the only difference is that the maximum transition duration,
    hard-coded to 4.5 s in the original package, is exposed as max_duration_s. Verified: at max_duration_s=4.5 the output
    is identical to the original."""

    def __init__(self, *args, max_duration_s=4.5, **kwargs):
        super().__init__(*args, **kwargs)
        self.max_duration_s = max_duration_s

    def apply(self, raw_acc, mag_acc, mag_acc_r, time, dt, power_peaks):
        acc_still, still_starts, still_stops = _get_still(mag_acc, dt, self.mov_window, self.grav, self.thresh)
        still_dt = (still_stops - still_starts) * dt
        lstill_starts = still_starts[still_dt > self.long_still]
        lstill_stops = still_stops[still_dt > self.long_still]

        gfc = butter(self.grav_ord, 2 * self.grav_cut * dt, btype='low')
        vert = filtfilt(gfc[0], gfc[1], raw_acc, axis=0, padlen=None)
        vert /= np.linalg.norm(vert, axis=1, keepdims=True)

        v_acc = np.sum(vert * raw_acc, axis=1)

        sts = {}
        prev_int_start = -1
        prev_int_stop = -1

        for ppk in power_peaks:
            try:
                end_still = still_stops[still_stops < ppk][-1]
                if (time[ppk] - time[end_still]).total_seconds() > 2:
                    raise IndexError
            except IndexError:
                continue
            try:
                start_still = lstill_starts[lstill_starts > ppk][0]
                if (time[start_still] - time[ppk]).total_seconds() < 30:
                    still_at_end = True
                else:
                    raise IndexError
            except IndexError:
                start_still = int(ppk + (5 / dt))
                still_at_end = False

            if end_still < prev_int_start or start_still > prev_int_stop:
                v_vel, v_pos = _integrate_acc(v_acc[end_still:start_still] - self.grav, dt, still_at_end)
                prev_int_start = end_still
                prev_int_stop = start_still
                pos_zc = np.append(0, np.where(np.diff(np.sign(v_vel)) > 0)[0]) + end_still
                neg_zc = np.append(np.where(np.diff(np.sign(v_vel)) < 0)[0], v_vel.size - 1) + end_still

            if v_vel[ppk - prev_int_start] < self.thresh['transition velocity']:
                continue

            sts_start = end_still

            try:
                sts_end = neg_zc[neg_zc > ppk][0]
            except IndexError:
                continue

            if (time[sts_end] - time[sts_start]).total_seconds() > self.max_duration_s:
                continue
            if (time[ppk] - time[sts_start]).total_seconds() > self.dur_factor * (time[sts_end]
                                                                                  - time[ppk]).total_seconds():
                continue
            t_start_i = sts_start - prev_int_start
            t_end_i = sts_end - prev_int_start
            if t_start_i == t_end_i:
                continue
            if (v_pos[t_end_i] - v_pos[t_start_i]) < self.thresh['stand displacement']:
                continue

            if len(sts) > 0:
                if (time[sts_start] - sts[list(sts.keys())[-1]].end_time).total_seconds() > 0.4:
                    sts[f'{time[sts_start]}'] = self.tq.quantify((time[sts_start], time[sts_end]), 1 / dt,
                                                                 raw_acc[sts_start:sts_end],
                                                                 mag_acc[sts_start:sts_end],
                                                                 mag_acc_r[sts_start:sts_end],
                                                                 v_vel[t_start_i:t_end_i], v_pos[t_start_i:t_end_i])
            else:
                sts[f'{time[sts_start]}'] = self.tq.quantify((time[sts_start], time[sts_end]), 1 / dt,
                                                             raw_acc[sts_start:sts_end],
                                                             mag_acc[sts_start:sts_end],
                                                             mag_acc_r[sts_start:sts_end],
                                                             v_vel[t_start_i:t_end_i], v_pos[t_start_i:t_end_i])

        vd = [sts[i].v_displacement for i in sts]
        if len(vd) > 0:
            vd_high_diff = np.array(vd) < self.disp_factor * np.median(vd)
            for elem in np.array(list(sts.keys()))[vd_high_diff]:
                del sts[elem]

        return sts


def collect_adamowicz_events(accel_data, gyro_data, fs, lowpass_cutoff=5.0, power_std_trim=1,
                               transition_velocity=0.2, max_duration_s=4.5):
    """Runs Adamowicz (AccelerationFilter + StillnessTunable, bypassing the
    Sit2Stand wrapper, which does not expose power_std_trim). Returns the list of events (t_start_s, t_end_s)
    -- STS only, by design of Adamowicz."""
    accel_arr = accel_data[['x', 'y', 'z']].to_numpy()
    time_us = (np.arange(len(accel_arr)) / fs * 1e6).astype(np.int64)

    acc_filt = AccelerationFilter(power_std_trim=power_std_trim, power_std_height=True,
                                    lowpass_cutoff=lowpass_cutoff)
    try:
        filt_accel, rec_accel, power, power_peaks = acc_filt.apply(accel_arr, fs)
    except Exception:
        return []

    timestamps, dt = process_timestamps(time_us, accel_arr, time_units='us', conv_kw=None,
                                          window=False, hours=None)

    detector = StillnessTunable(thresholds={'transition velocity': transition_velocity},
                                  max_duration_s=max_duration_s)
    try:
        sts = detector.apply(accel_arr, filt_accel, rec_accel, timestamps, dt, power_peaks)
    except Exception:
        return []

    events = []
    for k, v in sts.items():
        t_start = (v.start_time - timestamps[0]).total_seconds()
        t_end = (v.end_time - timestamps[0]).total_seconds()
        events.append((t_start, t_end))
    return events


def _collect_jas_events(accel_data, gyro_data, fs, want_type, lp_cutoff_hz, val_max_duration,
                          peak_height, gyro_asym_thresh):
    """Runs JASDetector and returns the list of events (t_start_s, t_end_s) of the
    requested type (want_type=‘STS’ or ‘SdS’). val_min_vdisp/disp_threshold_m/val_max_vdisp/
    val_min_gap are FIXED at values already known to work (not at the library defaults,
    which proved to be too strict and rejected every candidate for this data—see
    diagnosis: default val_max_vdisp=0.7 versus the required 2.0)."""

    acc1 = np.array(accel_data / 9.81)
    gyr1 = np.array(gyro_data)
    ts = np.arange(acc1.shape[0]) / fs

    detector = JASDetector(
        lp_cutoff_hz=lp_cutoff_hz, val_max_duration=val_max_duration,
        peak_height=peak_height, gyro_asym_thresh=gyro_asym_thresh,
        val_min_vdisp=0.1, disp_threshold_m=0.1, val_max_vdisp=2.0, val_min_gap=0.5,
        verbose=False,
    )
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            preds = detector.predict(accel=acc1, gyro=gyr1, time=ts)
    except Exception:
        return []

    if preds is None or len(preds) == 0:
        return []

    want_label = "sit2stand" if want_type == "STS" else "stand2sit"
    events = []
    for _, row in preds.iterrows():
        if row['transition_type'] == want_label:
            events.append((float(row['start_time']), float(row['end_time'])))
    return events



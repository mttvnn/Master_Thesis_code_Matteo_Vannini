    base_params = {**JAS_FIXED_BASE, **r1_params}
    n_jobs = os.cpu_count() if N_JOBS == -1 else N_JOBS
    chunks = [list(c) for c in np.array_split(np.arange(len(combos)), max(1, n_jobs)) if len(c)]
    res, gold_n = {}, {}

    for test_choice in TESTS_R2:
        print(f"  === {test_choice} ===")

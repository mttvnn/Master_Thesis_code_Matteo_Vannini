def _iou(interval_a, interval_b, fs_local=100):
    t0 = min(interval_a[0], interval_b[0])
    t1 = max(interval_a[1], interval_b[1])
    n_local = max(int(round((t1 - t0) * fs_local)), 1)
    t = np.linspace(t0, t1, n_local, endpoint=False)
    vec_a = (t >= interval_a[0]) & (t < interval_a[1])
    vec_b = (t >= interval_b[0]) & (t < interval_b[1])
    if not vec_a.any() and not vec_b.any():
        return 0.0
    return jaccard_score(vec_a, vec_b)


def evaluate_vs_gold(gt_intervals, pred_intervals, iou_threshold=0.5, fs=100):
    """Matching greedy basedon IoU: returns (tp, fp, gold_total)."""
    tp, fp = 0, 0
    used_gt = set()
    for (s, e) in pred_intervals:
        best_iou, best_idx = 0, -1
        for idx, (gs, ge) in enumerate(gt_intervals):
            if idx in used_gt:
                continue
            iou = _iou((s, e), (gs, ge), fs_local=int(fs))
            if iou > best_iou:
                best_iou, best_idx = iou, idx
        if best_iou >= iou_threshold:
            used_gt.add(best_idx)
            tp += 1
        else:
            fp += 1
    return tp, fp, len(gt_intervals)


def iou_via_jaccard_score(interval_a, interval_b, fs=100):
    t0 = min(interval_a[0], interval_b[0])
    t1 = max(interval_a[1], interval_b[1])
    n = max(int(round((t1 - t0) * fs)), 1)
    t = np.linspace(t0, t1, n, endpoint=False)
    vec_a = (t >= interval_a[0]) & (t < interval_a[1])
    vec_b = (t >= interval_b[0]) & (t < interval_b[1])
    if not vec_a.any() and not vec_b.any():
        return 0.0
    return jaccard_score(vec_a, vec_b)


def evaluate_IMU_vs_GD(ground_truth_intervals, predicted_intervals, iou_threshold=0.5, fs=100):
    """STANDARD classification (strict, object-detection-style, PASCAL VOC/COCO): a
    predicted object is a TP if it has an IoU >= the threshold with a gold label that has not yet been matched; otherwise, it is an FP. A
    gold label is a TP if it is matched by a predicted object with an IoU >= the threshold; otherwise, it is an FN. No “near-miss”
    'no result'—every predicted object has a result, every ground truth has a result, calculated
    independently"""
    used_gt = set()
    tp = 0
    fp = 0

    for pred_idx, (pred_start, pred_end) in enumerate(predicted_intervals):
        best_iou, best_gt_idx = 0, -1
        for gt_idx, (gt_start, gt_end) in enumerate(ground_truth_intervals):
            if gt_idx in used_gt:
                continue
            iou = iou_via_jaccard_score((pred_start, pred_end), (gt_start, gt_end), fs=fs)
            if iou > best_iou:
                best_iou, best_gt_idx = iou, gt_idx

        if best_iou >= iou_threshold:
            tp += 1
            used_gt.add(best_gt_idx)
        else:
            fp += 1

    fn = len([i for i in range(len(ground_truth_intervals)) if i not in used_gt])

    return {"TP": tp, "FP": fp, "FN": fn}




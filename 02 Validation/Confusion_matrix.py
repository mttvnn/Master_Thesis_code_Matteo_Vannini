def compute_performance(df_imu, algo_event_types, dataset_label):
    results = []
    for group_label, tests_in_group in TEST_GROUPS.items():
        for algo, ev_types in algo_event_types.items():
            algo_df_full = df_imu[df_imu['Algorithm'] == algo]
            if algo_df_full.empty:
                continue
            for ev_type in ev_types:
                tp = fp = fn = 0
                algo_df = algo_df_full[(algo_df_full['Type'] == ev_type) &
                                       (algo_df_full['Test'].isin(tests_in_group))]
                gs_type_df = df_gs[(df_gs['Type'] == ev_type) & (df_gs['Test'].isin(tests_in_group))]

                groups = pd.concat([algo_df[['PatientID', 'Test']],
                                    gs_type_df[['PatientID', 'Test']]]).drop_duplicates()

                for _, row in groups.iterrows():
                    pid, test = row['PatientID'], row['Test']
                    a_events = algo_df[(algo_df['PatientID'] == pid) & (algo_df['Test'] == test)]
                    g_events = gs_type_df[(gs_type_df['PatientID'] == pid) & (gs_type_df['Test'] == test)]
                    gt_intervals = list(zip(g_events['T_Start_s'], g_events['T_End_s']))
                    pred_intervals = list(zip(a_events['T_Start_s'], a_events['T_End_s']))
                    r = evaluate_IMU_vs_GD(gt_intervals, pred_intervals, iou_threshold=IOU_THRESHOLD, fs=IOU_FS)
                    tp += r['TP']; fp += r['FP']; fn += r['FN']

                precision = tp / (tp + fp) if (tp + fp) > 0 else 0
                sensitivity = tp / (tp + fn) if (tp + fn) > 0 else 0
                f1 = 2 * precision * sensitivity / (precision + sensitivity) if (precision + sensitivity) > 0 else 0
                results.append({'Dataset': dataset_label, 'Group': group_label, 'Algorithm': algo, 'Type': ev_type,
                                'TP': tp, 'FP': fp, 'FN': fn, 'Precision': precision,
                                'Sensitivity': sensitivity, 'F1-Score': f1})
    return pd.DataFrame(results)


def load_patient_info(info_mat_path, tm_choice='TimeMeasure1'):
    """Reads the WalkingAid_01 (numeric code) and WalkingAid_Description (free text) fields
    from a patient's infoForAlgo.mat file, handling both the v7.3 and v7-or-earlier .mat
    formats. If the file is missing, or a specific field inside it is missing, this function
    quietly falls back to sensible defaults (no walking aid) rather than raising an error --
    walking-aid info is only used for reporting/context, so a missing value shouldn't stop
    the rest of the analysis.
    Note: an older version of this pipeline also read an 'INDIP_DataUsed' field here, but
    that only mattered for choosing which pressure-insole data to trust and is not relevant
    to this IMU-only pipeline, so it has been dropped."""
    info = {'WalkingAid_01': 0, 'WalkingAid_Description': ''}
    if info_mat_path is None or not os.path.exists(info_mat_path):
        return info

    fmt = detect_mat_format(info_mat_path)
    if fmt == 'v7.3':
        with h5py.File(info_mat_path, 'r') as mat:
            root = mat['infoForAlgo']
            if _has(root, tm_choice, True):
                tm = _get(root, tm_choice, True)
                if _has(tm, 'WalkingAid_01', True):
                    info['WalkingAid_01'] = float(np.array(_get(tm, 'WalkingAid_01', True)).squeeze())
                if _has(tm, 'WalkingAid_Description', True):
                    try:
                        info['WalkingAid_Description'] = _to_str(_get(tm, 'WalkingAid_Description', True)[()])
                    except Exception:
                        pass
    elif fmt == 'v7_or_earlier':
        mat = sio.loadmat(info_mat_path, struct_as_record=False, squeeze_me=True)
        root = mat['infoForAlgo']
        if _has(root, tm_choice, False):
            tm = _get(root, tm_choice, False)
            if _has(tm, 'WalkingAid_01', False):
                info['WalkingAid_01'] = _get(tm, 'WalkingAid_01', False)
            if _has(tm, 'WalkingAid_Description', False):
                info['WalkingAid_Description'] = _get(tm, 'WalkingAid_Description', False)
    return info


def extract_imu_data(trial_obj, is_v73=False):
    """Extracts the LowerBack accelerometer/gyroscope arrays out of a single Trial object
    (i.e. data.TimeMeasure.Test.Trial), and returns them as two pandas DataFrames ready to be
    fed into the Pham/KielMAT and Sit2StandPy/Adamowicz algorithms further down the notebook.
    Mirrors the navigation style used in the original insoles/stereo pipeline's
    extract_sensors_data(), for consistency.

    Returns a 3-tuple (accel_data, gyro_data, status). On success, status is the literal
    string "OK" and accel_data/gyro_data are DataFrames with columns 'x', 'y', 'z'. On
    failure (a required field is missing, or something unexpected happens while reading),
    accel_data and gyro_data are both None and status is a human-readable message explaining
    what went wrong -- callers check `if accel_data is None:` to detect failure, and can
    print/log the status message for debugging.
    """
    try:
        if not _has(trial_obj, 'SU', is_v73):
            return None, None, f"'SU' missing in Trial. Available fields: {_fields(trial_obj, is_v73)}"
        su = _get(trial_obj, 'SU', is_v73)

        if not _has(su, 'LowerBack', is_v73):
            return None, None, f"'LowerBack' missing in SU. Available fields: {_fields(su, is_v73)}"
        lb = _get(su, 'LowerBack', is_v73)

        if not _has(lb, 'Acc', is_v73) or not _has(lb, 'Gyr', is_v73):
            return None, None, f"Acc/Gyr missing inside LowerBack. Available fields: {_fields(lb, is_v73)}"

        acc = np.array(_get(lb, 'Acc', is_v73))
        gyr = np.array(_get(lb, 'Gyr', is_v73))
    except Exception as e:
        return None, None, f"Exception while reading SU.LowerBack: {type(e).__name__}: {e}"

    # The raw arrays can come out as either (n_samples, 3) or (3, n_samples) depending on how
    # MATLAB stored them -- transpose if needed so we always end up with one row per sample.
    if acc.shape[0] == 3 and acc.shape[1] != 3:
        acc = acc.T
    if gyr.shape[0] == 3 and gyr.shape[1] != 3:
        gyr = gyr.T

    # The Axivity AX6 reports acceleration in units of "g" (multiples of Earth's gravity).
    # Both KielMAT/Pham and Sit2StandPy expect SI units (m/s^2), so we convert once, here,
    # right at the point of loading -- 1 g = 9.81 m/s^2. (The gyroscope, by contrast, is
    # already reported in deg/s, which is what both algorithms expect, so it is left as-is.)
    acc_ms2 = acc * 9.81

    # --- ASSIGNING IMU AXES ---
    # The output DataFrame columns are always named 'x', 'y', 'z' by convention, because
    # that's what KielMAT/Pham and the plotting code downstream expect to find. But WHICH
    # physical/raw column ends up under which letter is decided entirely by the
    # IMU_RAW_*_AXIS constants defined once in the "GLOBAL PARAMETERS" cell above -- there
    # are no "magic numbers" here. Concretely, for this dataset: 'z' = vertical, 'y' =
    # medio-lateral, 'x' = antero-posterior.
    accel_data = pd.DataFrame({
        'x': acc_ms2[:, IMU_RAW_VERTICAL_AXIS],
        'y': acc_ms2[:, IMU_RAW_MEDIOLATERAL_AXIS],
        'z': acc_ms2[:, IMU_RAW_ANTEROPOSTERIOR_AXIS],
    })

    # NOTE: an earlier version of this pipeline applied a sign flip here
    # (gyro_data['y'] = -gyr[:, IMU_RAW_MEDIOLATERAL_AXIS]) to compensate for an orientation
    # mismatch between this dataset and what KielMAT's Pham algorithm implicitly expects. That
    # flip has been removed on purpose in this version, so that Pham and Sit2StandPy are both
    # tested in their 'classic', fully unmodified form -- exactly as the original libraries
    # ship, with no dataset-specific corrections applied.
    gyro_data = pd.DataFrame({
        'x': gyr[:, IMU_RAW_VERTICAL_AXIS],
        'y': gyr[:, IMU_RAW_MEDIOLATERAL_AXIS],
        'z': gyr[:, IMU_RAW_ANTEROPOSTERIOR_AXIS],
    })

    return accel_data, gyro_data, "OK"


def load_imu_data(mat_path, tm_choice, test_choice, trial_choice):
    """Opens the .mat file at `mat_path`, walks down the structure
    TimeMeasure -> Test -> Trial, and calls extract_imu_data() on the requested trial.
    Mirrors load_sensors_data() from the original insoles/stereo pipeline.

    Handles both .mat formats transparently: for v7.3 files, the file is opened with h5py
    inside a `with` block (so it gets closed automatically when we're done, even if an error
    occurs) and we navigate starting from the top-level 'data' group; for older files, the
    whole file is loaded into memory at once with scipy.io.loadmat and we navigate the
    resulting nested struct object the same way.

    Returns the same 3-tuple format as extract_imu_data(): (accel_data, gyro_data, status)."""
    fmt = detect_mat_format(mat_path)
    is_v73 = (fmt == 'v7.3')

    def _navigate(tm_root):
        if not _has(tm_root, tm_choice, is_v73):
            return None, None, "TimeMeasure missing"
        tm = _get(tm_root, tm_choice, is_v73)
        if not _has(tm, test_choice, is_v73):
            return None, None, "Test missing"
        test = _get(tm, test_choice, is_v73)
        trial_keys = list(test.keys()) if is_v73 else dir(test)
        if trial_choice not in [t for t in trial_keys if 'Trial' in str(t)]:
            return None, None, "Trial missing"
        trial_obj = _get(test, trial_choice, is_v73)
        return extract_imu_data(trial_obj, is_v73)

    if is_v73:
        with h5py.File(mat_path, 'r') as mat:
            return _navigate(mat['data'])
    else:
        mat = sio.loadmat(mat_path, struct_as_record=False, squeeze_me=True)
        return _navigate(mat['data'])


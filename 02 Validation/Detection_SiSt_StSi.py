# --------------------------- IoU e classification ---------------------------
def interval_iou(a, b, fs=IOU_FS):
    """Jaccard Index (IoU) between two intervals, sampled on the same grid at fs Hz"""
    t0, t1 = min(a[0], b[0]), max(a[1], b[1])
    t = np.linspace(t0, t1, max(int(round((t1 - t0) * fs)), 1), endpoint=False)
    va, vb = (t >= a[0]) & (t < a[1]), (t >= b[0]) & (t < b[1])
    if not va.any() and not vb.any():
        return 0.0
    return float((va & vb).sum() / (va | vb).sum())


def classify_intervals(gt_intervals, pred_intervals, iou_threshold=IOU_THRESHOLD, fs=IOU_FS):
    """STANDARD Classification: Each predicted result is either a TP (IoU >= threshold with one
    unmatched gold) or an FP; each unmatched gold is an FN. Greedy matching in the order of the
    predicted results. Returns the indices so that individual events can also be plotted"""
    used_gt, tp_pairs, fp_idx = set(), [], []
    for pi, p in enumerate(pred_intervals):
        best, best_gi = 0.0, -1
        for gi, g in enumerate(gt_intervals):
            if gi in used_gt:
                continue
            v = interval_iou(p, g, fs)
            if v > best:
                best, best_gi = v, gi
        if best >= iou_threshold:
            tp_pairs.append((pi, best_gi, best))
            used_gt.add(best_gi)
        else:
            fp_idx.append(pi)
    fn_idx = [gi for gi in range(len(gt_intervals)) if gi not in used_gt]
    return {'tp_pairs': tp_pairs, 'fp_pred_idx': fp_idx, 'fn_gt_idx': fn_idx}


def evaluate_IMU_vs_GD(gt_intervals, pred_intervals, iou_threshold=IOU_THRESHOLD, fs=IOU_FS):
    """Counts only: {'TP', 'FP', 'FN'}."""
    c = classify_intervals(gt_intervals, pred_intervals, iou_threshold, fs)
    return {'TP': len(c['tp_pairs']), 'FP': len(c['fp_pred_idx']), 'FN': len(c['fn_gt_idx'])}


def prf(tp, fp, fn):
    """(precision, sensitivity, f1) from TP/FP/FN."""
    precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    sensitivity = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    f1 = 2 * precision * sensitivity / (precision + sensitivity) if (precision + sensitivity) > 0 else 0.0
    return precision, sensitivity, f1



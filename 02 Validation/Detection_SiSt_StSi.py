def _run_pham(pham, accel_data, gyro_data, fs, keep_types):
    """Runs a Pham instance and returns [(type, start, end)] filtered by keep_types"""
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        pham.detect(accel_data=accel_data, gyro_data=gyro_data, sampling_freq_Hz=int(fs),
                    tracking_system="imu", tracked_point="LowerBack", plot_results=False)
    if pham.postural_transitions_ is None or len(pham.postural_transitions_) == 0:
        return []
    pham.spatio_temporal_parameters()
    out = []
    for (_, row_pt), (_, row_par) in zip(pham.postural_transitions_.iterrows(), pham.parameters_.iterrows()):
        ev_type = 'STS' if row_par['type_of_postural_transition'] == 'sit to stand' else 'SdS'
        if ev_type in keep_types:
            onset, duration = float(row_pt['onset']), float(row_pt['duration'])
            out.append((ev_type, onset, onset + duration))
    return out


def _run_jas(jas_kwargs, accel_data, gyro_data, fs, keep_types):
    acc1, gyr1 = np.array(accel_data / 9.81), np.array(gyro_data)
    ts = np.arange(acc1.shape[0]) / fs
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        preds = JASDetector(verbose=False, **jas_kwargs).predict(accel=acc1, gyro=gyr1, time=ts)
    if preds is None or len(preds) == 0:
        return []
    out = []
    for _, row in preds.iterrows():
        ev_type = 'STS' if row['transition_type'] == 'sit2stand' else 'SdS'
        if ev_type in keep_types:
            out.append((ev_type, float(row['start_time']), float(row['end_time'])))
    return out



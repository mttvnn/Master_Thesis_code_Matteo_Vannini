def _walk(obj, path, is_v73):
    for key in path:
        obj = _get(obj, key, is_v73)
    arr = np.array(obj, dtype=float)
    return arr.T if is_v73 else arr

def _to_1d(sig, column=None):
    sig = np.squeeze(sig)
    if sig.ndim == 1:
        return sig
    if sig.shape[0] < sig.shape[1]:
        sig = sig.T
    return sig[:, column] if column is not None else sig.sum(axis=1)

def load_reference_signals(mat_path, tm_choice, test_choice, trial_choice):
    """Returns a dict containing ‘stereo’, ‘stereo_fs’, ‘ins_l’, ‘ins_r’, ‘ins_fs’ (None if missing)"""
    is_v73 = detect_mat_format(mat_path) == 'v7.3'
    out = {'stereo': None, 'stereo_fs': STEREO_FS, 'ins_l': None, 'ins_r': None, 'ins_fs': INSOLE_FS}

    def _read(trial):
        for key, path, fs_key, fs_path in [('stereo', STEREO_PATH, 'stereo_fs', STEREO_FS_PATH),
                                           ('ins_l', INSOLE_LEFT_PATH, 'ins_fs', INSOLE_FS_PATH),
                                           ('ins_r', INSOLE_RIGHT_PATH, None, None)]:
            try:
                out[key] = _walk(trial, path, is_v73)
                if fs_key is not None:
                    out[fs_key] = float(np.squeeze(_walk(trial, fs_path, is_v73)))
            except Exception as e:
                print(f"[!] {key} non disponibile: {type(e).__name__}: {e}")

    def _nav(root):
        trial = _get(_get(_get(root, tm_choice, is_v73), test_choice, is_v73), trial_choice, is_v73)
        _read(trial)

    if is_v73:
        with h5py.File(mat_path, 'r') as mat:
            _nav(mat['data'])
    else:
        mat = sio.loadmat(mat_path, struct_as_record=False, squeeze_me=True)
        _nav(mat['data'])
    return out



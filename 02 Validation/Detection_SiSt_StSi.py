class StillnessTunable(Stillness):
    """Identical to the original Stillness -- the only difference: configurable max_duration_s"""

    def __init__(self, *args, max_duration_s=4.5, **kwargs):
        super().__init__(*args, **kwargs)
        self.max_duration_s = max_duration_s

    def apply(self, raw_acc, mag_acc, mag_acc_r, time, dt, power_peaks):
        acc_still, still_starts, still_stops = _get_still(mag_acc, dt, self.mov_window, self.grav, self.thresh)
        still_dt = (still_stops - still_starts) * dt
        lstill_starts = still_starts[still_dt > self.long_still]
        gfc = butter(self.grav_ord, 2 * self.grav_cut * dt, btype='low')
        vert = filtfilt(gfc[0], gfc[1], raw_acc, axis=0, padlen=None)
        vert /= np.linalg.norm(vert, axis=1, keepdims=True)
        v_acc = np.sum(vert * raw_acc, axis=1)
        sts, prev_int_start, prev_int_stop = {}, -1, -1

        for ppk in power_peaks:
            try:
                end_still = still_stops[still_stops < ppk][-1]
                if (time[ppk] - time[end_still]).total_seconds() > 2: raise IndexError
            except IndexError:
                continue
            try:
                start_still = lstill_starts[lstill_starts > ppk][0]
                if (time[start_still] - time[ppk]).total_seconds() < 30:
                    still_at_end = True
                else:
                    raise IndexError
            except IndexError:
                start_still, still_at_end = int(ppk + (5 / dt)), False

            if end_still < prev_int_start or start_still > prev_int_stop:
                v_vel, v_pos = _integrate_acc(v_acc[end_still:start_still] - self.grav, dt, still_at_end)
                prev_int_start, prev_int_stop = end_still, start_still
                neg_zc = np.append(np.where(np.diff(np.sign(v_vel)) < 0)[0], v_vel.size - 1) + end_still

            if v_vel[ppk - prev_int_start] < self.thresh['transition velocity']: continue
            sts_start = end_still
            try:
                sts_end = neg_zc[neg_zc > ppk][0]
            except IndexError:
                continue
            if (time[sts_end] - time[sts_start]).total_seconds() > self.max_duration_s: continue
            if (time[ppk] - time[sts_start]).total_seconds() > self.dur_factor * (
                time[sts_end] - time[ppk]).total_seconds(): continue
            t_start_i, t_end_i = sts_start - prev_int_start, sts_end - prev_int_start
            if t_start_i == t_end_i: continue
            if (v_pos[t_end_i] - v_pos[t_start_i]) < self.thresh['stand displacement']: continue
            if sts and (time[sts_start] - sts[list(sts.keys())[-1]].end_time).total_seconds() <= 0.4:
                continue
            sts[f'{time[sts_start]}'] = self.tq.quantify(
                (time[sts_start], time[sts_end]), 1 / dt, raw_acc[sts_start:sts_end],
                mag_acc[sts_start:sts_end], mag_acc_r[sts_start:sts_end],
                v_vel[t_start_i:t_end_i], v_pos[t_start_i:t_end_i])

        vd = [sts[i].v_displacement for i in sts]
        if vd:
            for elem in np.array(list(sts.keys()))[np.array(vd) < self.disp_factor * np.median(vd)]:
                del sts[elem]
        return sts


def collect_adamowicz_events(accel_data, gyro_data, fs, lowpass_cutoff=5.0, power_std_trim=1,
                               transition_velocity=0.2, max_duration_s=4.5):
    accel_arr = accel_data[['x', 'y', 'z']].to_numpy()
    time_us = (np.arange(len(accel_arr)) / fs * 1e6).astype(np.int64)
    try:
        filt_accel, rec_accel, power, power_peaks = AccelerationFilter(
            power_std_trim=power_std_trim, power_std_height=True, lowpass_cutoff=lowpass_cutoff
        ).apply(accel_arr, fs)
    except Exception:
        return []
    timestamps, dt = process_timestamps(time_us, accel_arr, time_units='us', conv_kw=None,
                                          window=False, hours=None)
    try:
        sts = StillnessTunable(thresholds={'transition velocity': transition_velocity},
                                  max_duration_s=max_duration_s).apply(
            accel_arr, filt_accel, rec_accel, timestamps, dt, power_peaks)
    except Exception:
        return []
    return [((v.start_time - timestamps[0]).total_seconds(), (v.end_time - timestamps[0]).total_seconds())
            for v in sts.values()]


class PhamActiveLowpass(PhamPosturalTransitionDetection):
    """Identical to the original KielMAT library -- the only addition: a low-pass filter that is ACTUALLY
    applied to gyro_mediolateral. lp_filter_cutoff_hz=None -> original behavior."""

    def __init__(self, *args, lp_filter_cutoff_hz=None, lp_filter_order=4, **kwargs):
        super().__init__(*args, **kwargs)
        self.lp_filter_cutoff_hz = lp_filter_cutoff_hz
        self.lp_filter_order = lp_filter_order

    def detect(self, accel_data, gyro_data, sampling_freq_Hz, dt_data=None,
               tracking_system=None, tracked_point=None, plot_results=False):
        sampling_period = 1 / sampling_freq_Hz
        accel_data_arr = np.ascontiguousarray(accel_data)
        self.gyro_data = np.ascontiguousarray(np.deg2rad(gyro_data))
        vqf = VQF(sampling_period)
        out = vqf.updateBatch(self.gyro_data, accel_data_arr)
        accel_updated = np.zeros_like(accel_data_arr)
        gyro_updated = np.zeros_like(self.gyro_data)
        for t in range(accel_updated.shape[0]):
            accel_updated[t, :] = vqf.quatRotate(out["quat6D"][t, :], accel_data_arr[t, :])
        for t in range(gyro_updated.shape[0]):
            gyro_updated[t, :] = vqf.quatRotate(out["quat6D"][t, :], self.gyro_data[t, :])
        accel = accel_updated / 9.81
        self.gyro = np.rad2deg(gyro_updated)

        if np.ptp(self.gyro[:, 0]) > np.ptp(self.gyro[:, 1]) or np.var(self.gyro[:, 0]) > np.var(self.gyro[:, 1]):
            self.gyro_mediolateral = self.gyro[:, 0]
        else:
            self.gyro_mediolateral = self.gyro[:, 1]

        if self.lp_filter_cutoff_hz is not None:
            b, a = scipy.signal.butter(self.lp_filter_order, self.lp_filter_cutoff_hz / (sampling_freq_Hz / 2), btype='low')
            self.gyro_mediolateral = scipy.signal.filtfilt(b, a, self.gyro_mediolateral)

        time = np.arange(1, len(accel[:, 0]) + 1) * sampling_period
        tilt_angle_deg = _kielmat_preproc_module.tilt_angle_estimation(
            data=self.gyro_mediolateral, sampling_frequency_hz=sampling_freq_Hz)
        tilt_sin = np.sin(np.deg2rad(tilt_angle_deg))
        tilt_dwt = (_kielmat_preproc_module.wavelet_decomposition(data=tilt_sin, level=3, wavetype="coif5")
                    - _kielmat_preproc_module.wavelet_decomposition(data=tilt_sin, level=10, wavetype="coif5"))
        self.local_peaks, _ = scipy.signal.find_peaks(tilt_dwt, height=0.2, prominence=0.2)

        iZeroCr = np.where((self.gyro_mediolateral[:-1] * self.gyro_mediolateral[1:]) < 0)[0]
        gyro_y_diff = np.diff(self.gyro_mediolateral, axis=0)
        self.left_side = np.ones_like(self.local_peaks)
        self.right_side = len(self.gyro_mediolateral) * np.ones_like(self.local_peaks)

        for i in range(len(self.local_peaks)):
            pt = self.local_peaks[i]
            dist2peak = iZeroCr - pt
            left = dist2peak[dist2peak < 0]
            right = dist2peak[dist2peak > 0]
            for j in range(len(left) - 1, -1, -1):
                if gyro_y_diff[pt + left[j]] < 0 and -left[j] > (0.2 * sampling_freq_Hz):
                    if j > 0:
                        self.left_side[i] = pt + left[j]
                        break
            for j in range(len(right)):
                if gyro_y_diff[pt + right[j]] < 0 and right[j] > (0.2 * sampling_freq_Hz):
                    self.right_side[i] = pt + right[j]
                    break
            self.postural_transition_angle = np.abs(tilt_angle_deg[self.local_peaks] - tilt_angle_deg[self.left_side])
            if self.left_side[0] == 1:
                self.postural_transition_angle[0] = abs(
                    tilt_angle_deg[self.local_peaks[0]] - tilt_angle_deg[self.right_side[0]])
            duration = (self.right_side - self.left_side) / sampling_freq_Hz

        i = self.postural_transition_angle >= self.min_postural_transition_angle_deg
        self.postural_transitions_ = pd.DataFrame({
            "onset": self.left_side[i] / sampling_freq_Hz, "duration": duration[i],
            "event_type": "postural transition",
            "tracking_systems": tracking_system, "tracked_points": tracked_point,
        })
        return self


"""### 0.4 Data loading helper functions

MATLAB `.mat` files come in two very different flavors depending on how large the data is:
the "classic" format (readable with `scipy.io.loadmat`) and the newer "v7.3" format, which is
actually a standard HDF5 file under the hood and needs the `h5py` library instead. These two
formats expose the same logical structure (nested structs/groups) through completely
different Python APIs, so the helper functions below act as a thin, format-agnostic layer:
every function that actually navigates the file data (like `_has`/`_get`) checks which format
it's dealing with and calls the right underlying API, so the rest of the notebook doesn't
have to worry about the distinction at all.

"""

# --- Data loading helpers ---

def detect_mat_format(mat_path):
    """Distinguishes MATLAB .mat v7.3 files (HDF5-based, must be read with h5py) from
    v7-or-earlier files (read with scipy.io.loadmat), by inspecting the first bytes of the
    file. Every HDF5 file starts with a fixed 8-byte "magic number"
    (b'\\x89HDF\\r\\n\\x1a\\n'); MATLAB's older binary format does not, so checking the header
    is a reliable, fast way to tell the two apart without trying (and failing) to open the
    file with the wrong library first."""
    with open(mat_path, 'rb') as f:
        header = f.read(128)
    return 'v7.3' if header[:8] == b'\x89HDF\r\n\x1a\n' else 'v7_or_earlier'


def _to_str(val):
    """Converts a text field coming out of an h5py-loaded .mat file into a normal Python
    string. HDF5 stores strings as arrays of character codes (integers) rather than as
    native Python str objects, so this function reassembles those codes back into text.
    Falls back to a generic string conversion if the value isn't in the expected shape."""
    if isinstance(val, (bytes, str)):
        return val.decode() if isinstance(val, bytes) else val
    arr = np.array(val).squeeze()
    try:
        return ''.join(chr(c) for c in arr)
    except Exception:
        return str(arr)


# --- Small format-agnostic helpers ---
# The whole point of these three tiny functions is to hide the difference between the two
# .mat formats from the rest of the code. An h5py "group" object behaves like a dictionary
# (you check membership with `in` and access fields with `[...]`), while a struct produced by
# scipy.io.loadmat(struct_as_record=False) behaves like a regular Python object (you check
# for an attribute with hasattr() and access it with getattr()/dot notation). Every place in
# this notebook that needs to read a field from the raw .mat data calls _has()/_get() instead
# of using `in`/`[...]` or hasattr()/getattr() directly, passing along the is_v73 flag so the
# right underlying mechanism gets used automatically.
def _has(container, key, is_v73):
    """True if `container` has a field/key named `key`, regardless of which .mat format
    `container` came from."""
    return key in container.keys() if is_v73 else hasattr(container, key)


def _get(container, key, is_v73):
    """Reads the field/key named `key` out of `container`, regardless of which .mat format
    `container` came from."""
    return container[key] if is_v73 else getattr(container, key)


def _fields(container, is_v73):
    """Lists the field names available inside `container`. This is only used for building
    helpful diagnostic error messages when an expected field is missing (e.g. "'SU' missing
    in Trial. Available fields: [...]") -- it lets you immediately see what IS there instead
    of just knowing what ISN'T, which is very useful for fixing typos or an incorrect
    navigation path (TimeMeasure -> Test -> Trial -> SU -> LowerBack) without having to poke
    around the raw .mat file by hand."""
    if is_v73:
        return list(container.keys())
    return [a for a in dir(container) if not a.startswith('_')]



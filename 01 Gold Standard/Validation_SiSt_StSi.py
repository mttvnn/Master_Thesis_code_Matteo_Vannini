# Reads WalkingAid_01 / WalkingAid_Description and INDIP_DataUsed from
# infoForAlgo.mat, handling both .mat formats. Falls back to default
# values if the file or fields are missing.
def load_patient_info(info_mat_path, tm_choice='TimeMeasure1'):
    info = {'WalkingAid_01': 0, 'WalkingAid_Description': '', 'INDIP_DataUsed': ''}
    if info_mat_path is None or not os.path.exists(info_mat_path): return info

    fmt = detect_mat_format(info_mat_path)
    if fmt == 'v7.3':
        with h5py.File(info_mat_path, 'r') as mat:
            root = mat['infoForAlgo']
            if tm_choice in root.keys():
                tm = root[tm_choice]
                if 'WalkingAid_01' in tm.keys():
                    info['WalkingAid_01'] = float(np.array(tm['WalkingAid_01']).squeeze())
                if 'WalkingAid_Description' in tm.keys():
                    try: info['WalkingAid_Description'] = _to_str(tm['WalkingAid_Description'][()])
                    except: pass
                if 'INDIP_DataUsed' in tm.keys():
                    try: info['INDIP_DataUsed'] = _to_str(tm['INDIP_DataUsed'][()])
                    except: pass
    elif fmt == 'v7_or_earlier':
        mat = sio.loadmat(info_mat_path, struct_as_record=False, squeeze_me=True)
        root = mat['infoForAlgo']
        if hasattr(root, tm_choice):
            tm = getattr(root, tm_choice)
            if hasattr(tm, 'WalkingAid_01'): info['WalkingAid_01'] = getattr(tm, 'WalkingAid_01')
            if hasattr(tm, 'WalkingAid_Description'): info['WalkingAid_Description'] = getattr(tm, 'WalkingAid_Description')
            if hasattr(tm, 'INDIP_DataUsed'): info['INDIP_DataUsed'] = getattr(tm, 'INDIP_DataUsed')
    return info

# Interprets the INDIP_DataUsed flag to decide whether both insoles are
# usable, or only one of them.
def check_insoles_validity(info):
    flag = str(info.get('INDIP_DataUsed', '')).lower()
    if not flag or 'not used' not in flag:
        return 'both', "Both valid"
    if 'left' in flag:
        return 'right_only', "Right ONLY (Left discarded)"
    if 'right' in flag:
        return 'left_only', "Left ONLY (Right discarded)"
    return 'both', "Unknown (Forced Both)"

# Sums the per-sensor NormalizedPressure array of one insole into a
# single total-pressure time series (dimensionless, not Newtons).
def get_force_array(foot_struct):
    try:
        if hasattr(foot_struct, 'keys') and 'NormalizedPressure' in foot_struct.keys():
            val = np.array(foot_struct['NormalizedPressure'])
            return np.sum(val.T if val.shape[0] < val.shape[1] else val, axis=1).squeeze()
        elif hasattr(foot_struct, 'NormalizedPressure'):
            val = np.array(foot_struct.NormalizedPressure)
            return np.sum(val.T if len(val.shape) > 1 and val.shape[0] < val.shape[1] else val, axis=1).squeeze()
    except: pass
    return None

# Extracts total plantar pressure (Left+Right, or one foot if the other
# was flagged invalid) and the 3D trajectory of the "DYNA0" stereo marker.
def extract_sensors_data(trial_obj, is_v73=False, insoles_validity='both'):
    insoles_force = None
    stereo_marker = None
    try:
        stds = trial_obj['Standards'] if is_v73 else trial_obj.Standards

        # Extract insoles data
        if ('PressureInsoles_raw' in stds.keys() if is_v73 else hasattr(stds, 'PressureInsoles_raw')):
            insoles = stds['PressureInsoles_raw'] if is_v73 else stds.PressureInsoles_raw
            f_l = get_force_array(insoles['LeftFoot'] if is_v73 else insoles.LeftFoot)
            f_r = get_force_array(insoles['RightFoot'] if is_v73 else insoles.RightFoot)

            if insoles_validity == 'left_only':
                insoles_force = f_l
            elif insoles_validity == 'right_only':
                insoles_force = f_r
            else:
                if f_l is not None and f_r is not None:
                    m = min(len(f_l), len(f_r))
                    insoles_force = f_l[:m] + f_r[:m]
                else:
                    insoles_force = f_l if f_l is not None else f_r

        # Extract stereophotogrammetry data
        if ('Stereophoto_raw' in stds.keys() if is_v73 else hasattr(stds, 'Stereophoto_raw')):
            stereo = stds['Stereophoto_raw'] if is_v73 else stds.Stereophoto_raw
            mrks = stereo['Mrks'] if is_v73 else stereo.Mrks
            keys = list(mrks.keys()) if is_v73 else [attr for attr in dir(mrks) if not attr.startswith('_')]

            target_marker = next((k for k in keys if 'DYNA0' in k.upper()), None)
            if target_marker:
                val = np.array(mrks[target_marker]) if is_v73 else np.array(getattr(mrks, target_marker))
                if val.shape[0] == 3 and val.shape[1] > 3: val = val.T
                stereo_marker = val

    except: pass
    return insoles_force, stereo_marker

# Navigates TimeMeasure -> Test -> Trial and calls extract_sensors_data()
# on the requested trial.
def load_sensors_data(mat_path, tm_choice, test_choice, trial_choice, insoles_validity='both'):
    fmt = detect_mat_format(mat_path)
    if fmt == 'v7.3':
        with h5py.File(mat_path, 'r') as mat:
            tm_root = mat['data']
            if tm_choice not in tm_root.keys(): return None, None, "TimeMeasure missing"
            tm = tm_root[tm_choice]
            if test_choice not in tm.keys(): return None, None, "Test missing"
            test = tm[test_choice]
            if trial_choice not in [t for t in test.keys() if 'Trial' in str(t)]: return None, None, "Trial missing"
            ins, ste = extract_sensors_data(test[trial_choice], True, insoles_validity)
            return ins, ste, "OK"
    else:
        mat = sio.loadmat(mat_path, struct_as_record=False, squeeze_me=True)
        tm_root = mat['data']
        if not hasattr(tm_root, tm_choice): return None, None, "TimeMeasure missing"
        tm = getattr(tm_root, tm_choice)
        if not hasattr(tm, test_choice): return None, None, "Test missing"
        test = getattr(tm, test_choice)
        if trial_choice not in [t for t in dir(test) if 'Trial' in str(t)]: return None, None, "Trial missing"
        ins, ste = extract_sensors_data(getattr(test, trial_choice), False, insoles_validity)
        return ins, ste, "OK"

# ============================= DETECTION ALGORITHMS (STS & SdS) =============================

def detect_true_sts_from_insoles(insoles_data, fs_insoles=100.0, decrease_threshold=0.10, TEST_CHOICE=None, detect_sts=1, detect_sds=1):
    if insoles_data is None or len(insoles_data) == 0: return None
    # Low-pass filter (2 Hz cutoff) to smooth out sensor noise before
    # trying to detect any transition on the raw signal.
    b, a = butter(2, 2.0 / (fs_insoles / 2), btype='low')
    smoothed = filtfilt(b, a, insoles_data)

    total_len = len(smoothed)
    n_base = int(fs_insoles)  # one second of samples, used as the baseline window
    if total_len < n_base * 3: return None  # signal too short to be a real trial

    # Initial baseline: assume the patient is sitting still for the first
    # second of the recording, so its median pressure is the "seated weight".
    feet_weight = np.median(smoothed[:n_base])
    decrease_thr_val = feet_weight - (decrease_threshold * feet_weight)

    # Global baseline: median pressure over the middle 50% of the whole
    # recording, used later as a rough estimate of standing body weight.
    start_center = int(total_len * 0.25)
    end_center = int(total_len * 0.75)
    global_body_weight = np.median(smoothed[start_center:end_center])

    events = []
    t3_list = []

    # =========================================================================
    # 1. SIT-TO-STAND (STS) PIPELINE
    # =========================================================================
    if detect_sts == 1:
        search_start = n_base
        # t1 candidate: first point where pressure drops more than
        # decrease_threshold (10%) below the seated baseline.
        below = np.where(smoothed[search_start:] < decrease_thr_val)[0]

        if len(below) == 0: # Fallback for mild drops
            below = np.where(smoothed[search_start:] < feet_weight - (0.05 * feet_weight))[0]

        if len(below) > 0:
            t1_idx = search_start + below[0]
            body_weight = global_body_weight

            # Look for t3 (end of standing up): the first peak in pressure
            # that reaches body weight after t1.
            segment = smoothed[t1_idx:]
            if len(segment) > 0:
                peaks_rel, _ = find_peaks(segment, height=body_weight, distance=int(fs_insoles*0.2))
                t3_idx = None
                if len(peaks_rel) == 0:
                    # No clear peak: fall back to the first point that gets
                    # close (95%) to body weight.
                    after_t1 = np.where(segment >= body_weight * 0.95)[0]
                    if len(after_t1) > 0: t3_idx = t1_idx + after_t1[0]
                else:
                    # There is a peak: check what happens right after it,
                    # in case the patient sways and briefly dips below body
                    # weight again before settling.
                    peak_idx = t1_idx + peaks_rel[0]
                    after_peak = smoothed[peak_idx:]
                    below_after_peak = np.where(after_peak < body_weight)[0]

                    if len(below_after_peak) == 0:
                        # Never dips again after the peak: that peak is t3.
                        t3_idx = peak_idx
                    else:
                        # Dips after the peak, so find when it rises back to
                        # body weight - that's the real end of the transition.
                        dip_idx = peak_idx + below_after_peak[0]
                        after_dip = smoothed[dip_idx:]
                        rise_after_dip = np.where(after_dip >= body_weight)[0]
                        t3_idx = dip_idx if len(rise_after_dip) == 0 else dip_idx + rise_after_dip[0]

                if t3_idx is not None:
                    events.append((t1_idx / fs_insoles, t3_idx / fs_insoles, 'STS'))
                    t3_list.append(t3_idx)
                    durata_idx = t3_idx - t1_idx
                    # Skip ahead past this transition (plus a safety margin)
                    # before looking for the next one.
                    search_start = t3_idx + max(durata_idx * 2, int(2.0 * fs_insoles))

        # Test11 has several sit-stand-sit cycles in one trial (daily
        # activities), so keep searching for more STS events after the
        # first one instead of stopping here.
        if TEST_CHOICE == 'Test11':
            # Rough reference for "definitely standing" pressure, used to
            # tell a genuine stand-up apart from noise later in the loop.
            global_stand_pressure = np.percentile(smoothed, 95)
            if global_stand_pressure < feet_weight * 1.2:
                global_stand_pressure = feet_weight * 1.5

            while search_start < total_len:
                below = np.where(smoothed[search_start:] < decrease_thr_val)[0]
                if len(below) == 0: break

                t1_cand = search_start + below[0]
                # Look at a short window just before this candidate to see
                # what the patient was doing (already standing? walking?).
                idx_past_start = max(0, t1_cand - int(2.5 * fs_insoles))
                idx_past_end = max(0, t1_cand - int(0.2 * fs_insoles))

                if idx_past_end > idx_past_start:
                    picchi_passati = np.percentile(smoothed[idx_past_start:idx_past_end], 90)
                    peso_seduto_locale = np.median(smoothed[idx_past_start:idx_past_end])
                    # If the patient was already close to standing pressure
                    # just before this candidate, it's probably not a fresh
                    # sit-to-stand - skip ahead and keep looking.
                    if picchi_passati > global_stand_pressure * 0.75:
                        search_start = t1_cand + int(1.0 * fs_insoles)
                        continue
                else:
                    peso_seduto_locale = feet_weight

                # The pressure drop has to hold for at least 0.2s, otherwise
                # it's likely just noise rather than a real movement onset.
                dip_width = int(0.2 * fs_insoles)
                if t1_cand + dip_width < total_len and not np.all(smoothed[t1_cand : t1_cand + dip_width] < decrease_thr_val):
                    search_start = t1_cand + int(0.5 * fs_insoles)
                    continue

                # Check a window a couple of seconds after the candidate to
                # confirm the pressure actually rises toward standing level
                # (rules out false triggers that never turn into a stand-up).
                idx_3s = min(int(t1_cand + 2 * fs_insoles), total_len - 1)
                idx_8s = min(int(t1_cand + 6 * fs_insoles), total_len)
                finestra_bw = smoothed[idx_3s:idx_8s]

                if len(finestra_bw) == 0: break
                picco_post = np.percentile(finestra_bw, 85)
                mediana_post = np.median(finestra_bw)
                delta_alzata = global_stand_pressure - peso_seduto_locale

                if picco_post < peso_seduto_locale + (delta_alzata * 0.4) or mediana_post < peso_seduto_locale + (delta_alzata * 0.2):
                    # Rise isn't convincing enough: not a real stand-up,
                    # move on and keep searching further ahead.
                    search_start = t1_cand + int(2.0 * fs_insoles)
                    continue

                # Confirmed candidate: use the local seated/standing levels
                # around this specific event, instead of the global baseline,
                # since pressure can drift over a long Test11 recording.
                body_weight = peso_seduto_locale + 0.85 * (picco_post - peso_seduto_locale)
                t1_idx = t1_cand

                # Same t3 search as above, just repeated for this event.
                segment = smoothed[t1_idx:]
                peaks_rel, _ = find_peaks(segment, height=body_weight, distance=int(fs_insoles*0.2))

                t3_idx = None
                if len(peaks_rel) == 0:
                    after_t1 = np.where(segment >= body_weight * 0.95)[0]
                    if len(after_t1) > 0: t3_idx = t1_idx + after_t1[0]
                else:
                    peak_idx = t1_idx + peaks_rel[0]
                    after_peak = smoothed[peak_idx:]
                    below_after_peak = np.where(after_peak < body_weight)[0]

                    if len(below_after_peak) == 0:
                        t3_idx = peak_idx
                    else:
                        dip_idx = peak_idx + below_after_peak[0]
                        after_dip = smoothed[dip_idx:]
                        rise_after_dip = np.where(after_dip >= body_weight)[0]
                        t3_idx = dip_idx if len(rise_after_dip) == 0 else dip_idx + rise_after_dip[0]

                if t3_idx is None: break

                events.append((t1_idx / fs_insoles, t3_idx / fs_insoles, 'STS'))
                t3_list.append(t3_idx)
                search_start = t3_idx + max((t3_idx - t1_idx) * 2, int(2.0 * fs_insoles))

    # =========================================================================
    # 2. STAND-TO-SIT (SdS) PIPELINE
    # =========================================================================
    if detect_sds == 1:
        # Use the STS events already found to define, for each one, a
        # window right after it where the following sit-down should be.
        sts_starts = [int(ev[0] * fs_insoles) for ev in events if ev[2] == 'STS']
        sts_ends = [int(ev[1] * fs_insoles) for ev in events if ev[2] == 'STS']

        n_sts = len(sts_starts)

        for i in range(n_sts):
            window_start = sts_ends[i]

            if i == n_sts - 1:
                # Last STS in the trial: the window runs to the end of the
                # recording, and the seated baseline comes from the very end.
                window_end = total_len - 1
                local_seated_baseline = np.median(smoothed[-n_base:])
            else:
                # Otherwise the window stops where the next STS begins, and
                # the seated baseline comes from just before that next STS.
                window_end = sts_starts[i+1]
                local_seated_baseline = np.median(smoothed[max(window_start, window_end - int(1.0 * fs_insoles)):window_end])

            if window_start >= window_end:
                continue

            segment = smoothed[window_start : window_end + 1]
            sds_end_thr = local_seated_baseline + (decrease_threshold * feet_weight)
            # Search this window backwards (from the seated end toward the
            # standing start), since the sit-down we want is typically the
            # last thing that happens before the window's seated baseline.
            rev_segment = segment[::-1]

            above_end = np.where(rev_segment > sds_end_thr)[0]

            if len(above_end) > 0:
                rev_t1_idx = above_end[0]
                rev_search_segment = rev_segment[rev_t1_idx:]

                if len(rev_search_segment) > 0:
                    # Looking for a standing-pressure peak in the reversed
                    # segment - this marks (in reverse) where the patient
                    # was still standing just before sitting down.
                    peaks_rel, _ = find_peaks(rev_search_segment, height=global_body_weight*1.10, distance=int(fs_insoles*0.2))
                    rev_t3_idx = None

                    if len(peaks_rel) == 0:
                        after_t1 = np.where(rev_search_segment >= global_body_weight)[0]
                        if len(after_t1) > 0:
                            rev_t3_idx = rev_t1_idx + after_t1[0]
                    else:
                        first_peak = peaks_rel[0]
                        window_search_end = first_peak + int(2.5 * fs_insoles)
                        valid_peaks = [p for p in peaks_rel if p <= window_search_end]
                        picchi_valori = rev_search_segment[valid_peaks]
                        best_peak_local = valid_peaks[np.argmax(picchi_valori)]
                        rev_t3_idx = rev_t1_idx + best_peak_local

                if rev_t3_idx is not None:
                    # Remap the index found in the reversed segment back
                    # onto the normal (forward) timeline - this is t4, the
                    # start of the sit-down.
                    t4_idx = window_end - rev_t3_idx
                    forward_window = smoothed[t4_idx : window_end + 1]

                    if len(forward_window) > 0:
                        # t6 (end of sitting down) is simply the lowest
                        # pressure point between t4 and the end of the window.
                        t6_idx = t4_idx + np.argmin(forward_window)
                        if t6_idx > t4_idx:
                            events.append((t4_idx / fs_insoles, t6_idx / fs_insoles, 'SdS'))

    events.sort(key=lambda x: x[0])
    return events if len(events) > 0 else None



# Overwrites Start/End with the manually-annotated value, deletes false
# positives, and adds events the algorithm missed entirely - based on the
# manual_corrections table. Prints what changed for this patient.
def apply_manual_corrections(patient_id, eventi_start, eventi_end, eventi_tipo):
    # Only the corrections that belong to this patient and to the test
    # currently being run are relevant here.
    corrections_for_patient = [c for c in manual_corrections if c["PatientID"] == patient_id and c["Test"] == TEST_CHOICE]
    if not corrections_for_patient:
        return eventi_start, eventi_end, eventi_tipo

    # Work on copies so the original lists from the detection step aren't
    # mutated in place while we're still looping over them below.
    eventi_start = list(eventi_start)
    eventi_end = list(eventi_end)
    eventi_tipo = list(eventi_tipo)
    indices_to_delete = set()

    print(f"    -> ⚙️ [MANUAL OVERRIDE] Found manual corrections for patient {patient_id}:")
    for c in corrections_for_patient:
        # "Occurrence" picks which event of this type to correct, e.g. the
        # 2nd SdS detected for this patient, in chronological order.
        matching_idx = [i for i, t in enumerate(eventi_tipo) if t == c["Type"]]
        occ = c.get("Occurrence", 1)

        if occ <= len(matching_idx):
            idx = matching_idx[occ - 1]
            if c.get("Delete", False):
                # Marked as a false positive: remember its index and remove
                # it from all three lists at the end, once the loop is done.
                print(f"       * {c['Type']} (occ. {occ}) REMOVED (false positive).")
                indices_to_delete.add(idx)
            else:
                # Overwrite only the side(s) that were actually annotated -
                # Start and End can be corrected independently.
                if c.get("T_Start_s") is not None:
                    print(f"       * {c['Type']} (occ. {occ}) START changed: {eventi_start[idx]:.2f}s -> {c['T_Start_s']}s")
                    eventi_start[idx] = c["T_Start_s"]
                if c.get("T_End_s") is not None:
                    print(f"       * {c['Type']} (occ. {occ}) END changed:   {eventi_end[idx]:.2f}s -> {c['T_End_s']}s")
                    eventi_end[idx] = c["T_End_s"]
        else:
            # The algorithm didn't detect this many events of this type for
            # the patient - if it's a full correction (both Start and End
            # given) and not a delete request, add it as a brand new event.
            if not c.get("Delete", False):
                print(f"       * {c['Type']} added from a manual correction (missed by the algorithm).")
                if c.get("T_Start_s") is not None and c.get("T_End_s") is not None:
                    eventi_start.append(c["T_Start_s"])
                    eventi_end.append(c["T_End_s"])
                    eventi_tipo.append(c["Type"])

    # Remove any events flagged for deletion, all at once, so the indices
    # collected above stay valid throughout the loop above.
    if indices_to_delete:
        eventi_start = [e for i, e in enumerate(eventi_start) if i not in indices_to_delete]
        eventi_end   = [e for i, e in enumerate(eventi_end)   if i not in indices_to_delete]
        eventi_tipo  = [e for i, e in enumerate(eventi_tipo)  if i not in indices_to_delete]

    return eventi_start, eventi_end, eventi_tipo


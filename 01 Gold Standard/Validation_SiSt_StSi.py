# Distinguishes MATLAB .mat v7.3 files (HDF5-based, read with h5py)
# from v7/earlier files (read with scipy.io.loadmat), by inspecting the
# binary file header.
def detect_mat_format(mat_path):
    with open(mat_path, 'rb') as f:
        header = f.read(128)
    return 'v7.3' if header[:8] == b'\x89HDF\r\n\x1a\n' else 'v7_or_earlier'

# Converts a text field coming out of an h5py-loaded .mat file (stored
# as an array of character codes) into a normal Python string.
def _to_str(val):
    if isinstance(val, (bytes, str)): return val.decode() if isinstance(val, bytes) else val
    arr = np.array(val).squeeze()
    try: return ''.join(chr(c) for c in arr)
    except: return str(arr)

# Looks for the patient's main data file under Laboratory/, trying a
# few different filename spellings observed in this dataset.
def find_mat_path(base_drive, patient_id):
    for c in [f"{base_drive}/{patient_id}/Laboratory/data.mat",
              f"{base_drive}/{patient_id}/Laboratory/Data.mat",
              f"{base_drive}/{patient_id}/Laboratory/data_Laboratory.mat"]:
        if os.path.exists(c): return c
    return None

# Looks for the patient's infoForAlgo.mat metadata file (walking aid

# Plots the insoles and stereophotogrammetry signals for one patient,
# with the detected STS/SdS events highlighted. Returns the Figure object
# so the export cell can also embed it into the Excel report without
# re-plotting; show=False lets the export cell build the figure quietly.
def plot_patient_signals(patient_id, insoles_data, stereo_data, eventi_start, eventi_end, eventi_tipo, show=True):
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 7.2), sharex=True, gridspec_kw={'hspace': 0.42})

    # --- Panel 1: Pressure Insoles ---
    t_insoles = np.arange(len(insoles_data)) / 100.0
    ax1.plot(t_insoles, insoles_data, color=STEEL, linewidth=1.3)

    for start, end, tipo in zip(eventi_start, eventi_end, eventi_tipo):
        colore_fase = STEEL if tipo == 'STS' else SDS_COLOR
        ax1.axvspan(start, end, color=colore_fase, alpha=0.12)
        ax1.axvline(start, color=colore_fase, linewidth=1, linestyle='--' if tipo == 'SdS' else '-')
        ax1.axvline(end, color=colore_fase, linewidth=1, linestyle='--' if tipo == 'SdS' else '-')

    ax1.margins(y=0.15)
    ax1.set_ylabel("Pressure (a.u.)", fontsize=10.5, color=TEXT_DARK)
    ax1.grid(True, linestyle='--', linewidth=0.6, color=GRID_GRAY, alpha=0.8)
    ax1.spines[['top', 'right']].set_visible(False)
    ax1.tick_params(labelsize=9.5, colors=TEXT_DARK)
    ax1.tick_params(labelbottom=True)
    ax1.set_xlabel("Time (s)", fontsize=11, color=TEXT_DARK)

    # --- Panel 2: Stereophotogrammetry ---
    if stereo_data is not None and len(stereo_data) > 0:
        t_stereo = np.arange(len(stereo_data)) / 100.0
        ax2.plot(t_stereo, stereo_data[:, STEREO_VERTICAL_AXIS], color=BURGUNDY, linewidth=1.3)

        for start, end, tipo in zip(eventi_start, eventi_end, eventi_tipo):
            colore_fase = STEEL if tipo == 'STS' else SDS_COLOR
            ax2.axvspan(start, end, color=colore_fase, alpha=0.10)
            ax2.axvline(start, color=colore_fase, linewidth=1, linestyle='--' if tipo == 'SdS' else '-')
            ax2.axvline(end, color=colore_fase, linewidth=1, linestyle='--' if tipo == 'SdS' else '-')

        ax2.margins(y=0.15)
        ax2.set_ylabel("Position (mm)", fontsize=10.5, color=TEXT_DARK)
    else:
        ax2.text(0.5, 0.5, "Stereo data not available", ha='center', va='center',
                 transform=ax2.transAxes, fontsize=11, color=TEXT_DARK)

    ax2.set_xlabel("Time (s)", fontsize=11, color=TEXT_DARK)
    ax2.grid(True, linestyle='--', linewidth=0.6, color=GRID_GRAY, alpha=0.8)
    ax2.spines[['top', 'right']].set_visible(False)
    ax2.tick_params(labelsize=9.5, colors=TEXT_DARK)

    plt.tight_layout(rect=[0, 0, 1, 0.965])
    if show:
        plt.show()
    return fig

"""## 3. Manual corrections

Ground truth transcribed from Manual_Correction_STS_SDS.docx. Overwrites a wrong Start/End, deletes a false positive, or adds a missed event - per patient, test, event type, and occurrence (1 = first/only one).
"""

manual_corrections = _P["MANUAL_CORRECTIONS"]   # list of corrections (see participants_template.json)

"""## 4. Run the analysis

Processes every patient in PATIENT_IDS: loads the data, runs detection, applies the manual corrections, and prints a per-event summary. Keeps the signals and final events in memory for the next cells.
"""

print("STARTING BATCH ANALYSIS (INSOLES & STEREO)...\n" + "="*80)

success_count = 0
patient_results = []

for patient_id in PATIENT_IDS:
    mat_path = find_mat_path(BASE_DRIVE, patient_id)

    if not mat_path:
        print(f"\n\u274c [{patient_id}] data.mat NOT FOUND.")
        continue

    info_path = find_info_path(BASE_DRIVE, patient_id)
    p_info = load_patient_info(info_path, TM_CHOICE)

    aid_val = p_info.get('WalkingAid_01', 0)
    aid_desc = str(p_info.get('WalkingAid_Description', '')).strip()
    uses_aid = "NO"
    if aid_val == 1 or (aid_desc and aid_desc.lower() not in ['nan', 'none']):
        uses_aid = f"YES ({aid_desc})" if aid_desc else "YES"

    insoles_validity, validity_str = check_insoles_validity(p_info)
    insoles_data, stereo_data, status_msg = load_sensors_data(mat_path, TM_CHOICE, TEST_CHOICE, TRIAL_CHOICE, insoles_validity)

    if status_msg != "OK":
        print(f"\n\u26a0\ufe0f [{patient_id}] {status_msg}.")
        continue

    if insoles_data is None:
        print(f"\n\u26a0\ufe0f [{patient_id}] Insoles data empty or formatting is incorrect. (Aid: {uses_aid})")
        continue

    print(f"\n\u2705 [{patient_id}] Analysis completed | Aid: {uses_aid} | Insoles: {validity_str}")
    success_count += 1

    # Run detection
    risultato_algo = detect_true_sts_from_insoles(insoles_data, 100.0, 0.10, TEST_CHOICE)

    eventi_start, eventi_end, eventi_tipo = [], [], []
    if risultato_algo:
        for item in risultato_algo:
            if len(item) == 3:
                t_inizio, t_fine, tipo = item
            else:
                t_inizio, t_fine = item
                tipo = 'STS'
            eventi_start.append(t_inizio)
            eventi_end.append(t_fine)
            eventi_tipo.append(tipo)

    # Apply manual corrections BEFORE printing, so the printed summary
    # matches exactly what ends up in the plots and the Excel export.
    eventi_start, eventi_end, eventi_tipo = apply_manual_corrections(patient_id, eventi_start, eventi_end, eventi_tipo)

    if eventi_start:
        for start, end, tipo in zip(eventi_start, eventi_end, eventi_tipo):
            durata = end - start
            print(f"    -> [{tipo}] Start {start:.2f}s | End {end:.2f}s | Durata {durata:.2f}s")
    else:
        print(f"    -> Nessun evento trovato o transizione fallita.")

    patient_results.append((patient_id, insoles_data, stereo_data, eventi_start, eventi_end, eventi_tipo))

print("\n" + "="*80)
print(f"\U0001f3af ANALYSIS COMPLETED.")
print(f"\U0001f4ca Patients successfully processed (Valid insoles): {success_count} out of {len(PATIENT_IDS)}")
print("="*80 + "\n")

"""## 5. Plots

Draws the insoles + stereophotogrammetry plot for each patient, for on-screen review.
"""

for patient_id, insoles_data, stereo_data, eventi_start, eventi_end, eventi_tipo in patient_results:
    print(patient_id)
    plot_patient_signals(patient_id, insoles_data, stereo_data, eventi_start, eventi_end, eventi_tipo)

